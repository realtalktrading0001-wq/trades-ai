// Lightweight i18n. `translate(code, key, vars)` returns the string for a
// language code, falling back to English then the key itself. No React here so
// it can be imported anywhere without circular deps; the `useT` hook lives in
// useT.ts and reads the current language from AppContext.

export type LangCode = 'en' | 'hi' | 'es' | 'pt' | 'ru' | 'ar';

// Display names shown in the Language dropdown (value stored on the user).
export const LANGUAGE_OPTIONS = ['English', 'हिन्दी', 'Español', 'Português', 'Русский', 'العربية'];

export function langToCode(name: string | null | undefined): LangCode {
  const n = (name ?? '').toLowerCase();
  if (n.includes('हिन') || n.includes('hindi')) return 'hi';
  if (n.includes('españ') || n.includes('espan') || n.includes('spanish')) return 'es';
  if (n.includes('portug') || n.includes('português')) return 'pt';
  if (n.includes('рус') || n.includes('russ')) return 'ru';
  if (n.includes('عرب') || n.includes('arab')) return 'ar';
  return 'en';
}

export function isRTL(code: LangCode): boolean {
  return code === 'ar';
}

